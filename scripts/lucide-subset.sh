#!/usr/bin/env bash
# Rebuilds assets/fonts/lucide.ttf and src/icons.rs from the Lucide icon font, keeping only the
# icons listed below. Needs curl, python3 and uv (for fonttools). Add a name, run, commit both.
set -euo pipefail

VERSION=0.460.0
ICONS="
archive archive-restore bot maximize-2 minimize-2 send-horizontal square arrow-down-to-line arrow-up arrow-up-from-line check cherry
chevron-down chevron-right chevron-up chevrons-up-down circle circle-alert circle-check circle-dot cloud copy
download folder folder-open house git-branch git-branch-plus git-commit-horizontal git-compare-arrows
git-merge loader palette pencil plus sparkles info bug external-link refresh-cw rotate-ccw search settings star tag trash-2
tree-pine triangle-alert undo-2 upload x lock lock-open history user-round-pen
"

root=$(cd "$(dirname "$0")/.." && pwd)
tmp=$(mktemp -d)
trap 'rm -rf "$tmp"' EXIT
curl -sfL -o "$tmp/lucide.ttf" "https://unpkg.com/lucide-static@$VERSION/font/lucide.ttf"
curl -sfL -o "$tmp/info.json" "https://unpkg.com/lucide-static@$VERSION/font/info.json"

python3 -I - "$tmp/info.json" "$root/src/icons.rs" "$tmp/unicodes" $ICONS <<'EOF'
import json, sys
info_path, rs_path, uni_path, *names = sys.argv[1:]
info = json.load(open(info_path))
lines = [
    "//! Lucide outline icons (lucide-static, ISC licence), from the subset font",
    "//! `assets/fonts/lucide.ttf`. Each constant is the icon's private-use code point; put it in",
    "//! any text like a letter. Generated by `scripts/lucide-subset.sh`; add icons there.",
    "",
]
codes = []
for n in names:
    code = info[n]["encodedCode"].lstrip("\\")
    codes.append("U+" + code)
    lines.append(f'pub const {n.upper().replace("-", "_")}: &str = "\\u{{{code}}}";')
lines += ["", "#[cfg(test)]", "pub const ALL: &[&str] = &["]
lines += [f'    {n.upper().replace("-", "_")},' for n in names]
lines += ["];", ""]
open(rs_path, "w").write("\n".join(lines))
open(uni_path, "w").write(",".join(codes))
EOF

uvx --from fonttools pyftsubset "$tmp/lucide.ttf" --unicodes="$(cat "$tmp/unicodes")" \
    --output-file="$root/assets/fonts/lucide.ttf" --no-hinting --layout-features=''
echo "wrote assets/fonts/lucide.ttf and src/icons.rs"
